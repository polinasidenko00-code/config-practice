"""Исключения, которыми команды сообщают о результате работы."""


class CommandError(Exception):
    """Ошибка выполнения команды (неверные аргументы и т.п.).

    output - вывод, полученный до ошибки или для корректных
    аргументов (например, cat для части файлов); печатается
    перед сообщением об ошибке.
    """

    def __init__(self, message, output=""):
        """Сохранить сообщение об ошибке и частичный вывод."""
        super().__init__(message)
        self.output = output


class ExitRequest(Exception):
    """Запрос на завершение работы эмулятора с кодом возврата."""

    def __init__(self, code):
        """Сохранить код возврата для завершения эмулятора."""
        super().__init__(code)
        self.code = code
