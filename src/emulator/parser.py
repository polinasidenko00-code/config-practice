"""Простой парсер строки ввода эмулятора."""


def parse(line):
    """Разделить строку ввода на команду и аргументы по пробелам.

    Возвращает кортеж (имя команды, список аргументов).
    Для пустой строки или строки из одних пробелов
    возвращает (None, []).
    """
    parts = line.split()
    if not parts:
        return None, []
    return parts[0], parts[1:]
